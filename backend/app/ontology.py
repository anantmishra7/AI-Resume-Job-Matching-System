def normalize_skill(skill_str: str) -> str:
    """Normalize skill name using alias dictionary."""
    clean = skill_str.strip().lower()
    return SKILL_ALIASES.get(clean, skill_str.strip().title())

def get_skill_canonical_set() -> Set[str]:
    """Return all unique canonical skill names."""
    return set(SKILL_ALIASES.values())
